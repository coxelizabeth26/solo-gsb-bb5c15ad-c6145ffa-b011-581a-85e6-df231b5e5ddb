"""服务端唯一时钟来源。

所有「当前时间」判定（阶段边界）与所有记录的 created_at 都以此为唯一依据，
便于测试中猴子补丁单个函数即可控制全部时间来源，保证历史回放类测试的
时间戳确定性。

写入路径（创建事件、提交/批量提交承诺、揭示/批量揭示、延长、结算）在
请求入口只读取一次：该时刻同时用于阶段准入判定与本次记录 created_at 的
显式赋值，批量请求内各项共用同一时刻。即使读数与写入之间服务端真实时钟
恰好跨过某个截止点，也不会出现「准入判定属于一个阶段、记录时间却落入
下一阶段」的矛盾。模型上的 ``default=clock.now_utc`` 仅作兜底（如脚本
直接写库），路由创建记录时一律显式赋值。
"""

from datetime import datetime, timezone


def now_utc() -> datetime:
    """服务端当前 UTC 时间，全部截止判定与写入时间戳以此为唯一依据。"""
    return datetime.now(timezone.utc)
